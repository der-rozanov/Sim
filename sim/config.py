"""Параметры симулятора. Все числа физики живут здесь."""

from dataclasses import dataclass


@dataclass
class AircraftParams:
    """
    Параметры ЛА — FPV-самолёт классической схемы класса 1.8 м (РЕШ-20).

    Типовой высокоплан (Volantex Ranger 2000 / Skywalker 1900): m = 2 кг,
    прямоугольное крыло 1.8 × 0.25 м, ГО с РВ, ВО с РН, тянущий винт.
    Геометрия и масса — ОЦЕНКА [АВТОР: заменить замерами изделия].
    Аэродинамические производные посчитаны по геометрии учебными формулами
    (Nelson, Raymer, Roskam) — расчёт и формулы: checks/estimate_fpv_aero.py.
    ВМГ: T-Motor AT2814 900KV (паспорт) + APC 11×7E (продувка UIUC), АКБ 4S.
    Прежний набор (Aerosonde, B&M 2-е изд., РЕШ-18/19) — aerosonde_params().
    """

    # Тип ЛА — ключ реестра AIRCRAFT_TYPES; по нему viz/ выбирает 3D-модель
    name: str = "fpv"

    # --- Масса и инерция (радиусы инерции по Roskam) ---
    mass: float = 2.0      # кг
    Jx:   float = 0.1013   # кг·м², момент инерции крена
    Jy:   float = 0.1040   # кг·м², момент инерции тангажа
    Jz:   float = 0.1711   # кг·м², момент инерции рыскания
    Jxz:  float = 0.0      # кг·м², центробежный момент (мал для высокоплана)

    # --- Геометрия крыла ---
    S:    float = 0.45     # м², площадь крыла
    b:    float = 1.8      # м, размах
    c:    float = 0.25     # м, хорда (прямоугольное крыло)

    # --- Среда ---
    rho:  float = 1.2682   # кг/м³
    g:    float = 9.81     # м/с²

    # --- Аэродинамика: продольный канал ---
    # CL = CL(α) + CLq·q̂ + CLde·δe,  q̂ = c·q/(2Va)
    CL0:  float = 0.2636   # установка крыла 0°, профиль Clark-Y (α0L = −3.5°)
    CLa:  float = 4.936    # крыло + ГО с учётом скоса потока
    CLq:  float = 3.415
    CLde: float = 0.4256

    # CD = (1−σ)·[CDp + (CL0 + CLa·α)²/(π·e·AR)] + σ·[CDp + 2|sin α|³]
    #      + CDq·q̂ + CDde·|δe|
    CDp:  float = 0.0340   # эквивалентное трение + FPV-надстройки (Raymer)
    e_oswald: float = 0.8334   # Raymer, прямое крыло AR = 7.2
    CDq:  float = 0.0
    CDde: float = 0.0      # не оценивалось

    # Cm = Cm0 + Cma·α + Cmq·q̂ + Cmde·δe
    Cm0:  float = 0.00145  # установка ГО выбрана для δe = 0 на 16 м/с
    Cma:  float = -0.4936  # запас статической устойчивости 10 % САХ
    Cmq:  float = -11.27   # демпфирование тангажа (ГО + 10 %)
    Cmde: float = -1.277   # δe > 0 — нос вниз

    # --- Аэродинамика: боковой канал ---
    # C* = C*0 + C*_beta·β + C*_p·p̂ + C*_r·r̂ + C*_da·δa + C*_dr·δr,
    # p̂ = b·p/(2Va), r̂ = b·r/(2Va).
    # Croll — момент крена (в B&M C_l; переименован, чтобы не путать с Cl подъёмной силы)
    # Производные по p, r и Cn_da — на крейсерском CL = 0.28 (16 м/с)
    # Боковая сила
    CY0:     float = 0.0
    CY_beta: float = -0.1871
    CY_p:    float = 0.0208
    CY_r:    float = 0.1559
    CY_da:   float = 0.0
    CY_dr:   float = 0.1399
    # Момент крена
    Croll0:     float = 0.0
    Croll_beta: float = -0.0706   # поперечное V 3° + киль
    Croll_p:    float = -0.7664   # демпфирование крена
    Croll_r:    float = 0.1013
    Croll_da:   float = 0.4568    # элероны 50–95 % полуразмаха, 25 % хорды
    Croll_dr:   float = 0.00777
    # Момент рыскания
    Cn0:     float = 0.0
    Cn_beta: float = 0.0666       # > 0 — путевая устойчивость (киль − фюзеляж)
    Cn_p:    float = -0.0348
    Cn_r:    float = -0.0735      # демпфирование рыскания
    Cn_da:   float = -0.0381      # обратное рыскание элеронов
    Cn_dr:   float = -0.0583      # эффективность руля направления

    # Нелинейная модель CL (sigmoid-смешение, B&M ур. 4.9–4.10)
    # CL = (1 - sigma)*linear + sigma*flat_plate
    M_sigmoid: float = 50.0       # крутизна перехода
    alpha_stall: float = 0.2615   # рад ≈ 15° — даёт CL_max = 0.9·cl_max профиля = 1.215 при α ≈ 12.2°

    # --- Силовая установка: электромотор + винт (B&M 2-е изд., разд. 4.3) ---
    D_prop:   float = 0.2794    # м, APC 11×7E
    KV_rpm:   float = 900.0     # об/мин/В, T-Motor AT2814 900KV
    R_motor:  float = 0.082     # Ом
    i0:       float = 1.2       # А, ток холостого хода
    V_max:    float = 14.8      # В, АКБ 4S
    # CT(J), CQ(J) = C2·J² + C1·J + C0 — аппроксимация продувки UIUC APC 11×7E
    C_T2: float = -0.15819
    C_T1: float = -0.018756
    C_T0: float = 0.10922
    C_Q2: float = -0.020775
    C_Q1: float = 0.0094015
    C_Q0: float = 0.0068499

    # --- Критические углы атаки (привязаны к модели: максимум CL) ---
    alpha_warning: float = 0.1571   # рад ≈ 9°, предупреждение
    alpha_crit:    float = 0.2129   # рад ≈ 12.2°, критический УА (максимум CL)

    # --- Ограничения рулей ---
    delta_e_max: float =  0.4363   # рад ≈ +25°
    delta_e_min: float = -0.4363   # рад ≈ -25°
    delta_a_max: float = 0.4363    # рад ≈ ±25°, элероны
    delta_r_max: float = 0.4363    # рад ≈ ±25°, руль направления
    throttle_max: float = 1.0
    throttle_min: float = 0.0

    # --- Приводы рулей (sim/actuators.py, РЕШ-28) ---
    # Цифровой сервопривод класса 9–20 г: без нагрузки ≈ 0.10 с / 60°, под
    # аэродинамической нагрузкой ≈ вдвое медленнее; полоса контура положения ≈ 5 Гц.
    # ОЦЕНКА [АВТОР: паспорт сервоприводов изделия]. servo_tau = 0 и
    # servo_rate = inf — мгновенные рули (как до РЕШ-28).
    servo_tau:  float = 0.03       # с, постоянная времени привода
    servo_rate: float = 5.236      # рад/с ≈ 300 °/с, предельная скорость перекладки

    # --- Шасси и точки касания земли (sim/ground.py, docs/physics.md 4.6, РЕШ-25) ---
    # Связанная СК от ЦМ, м: x — вперёд, y — вправо, z — вниз. Трёхопорное шасси
    # с носовым колесом; точки сняты с 3D-модели (viz/aircraft3d.py, масштаб b/11)
    # — ОЦЕНКА [АВТОР: замерить изделие].
    gear_wheels: tuple = ((0.352, 0.0, 0.265),       # носовое (поворачивается от δr)
                          (-0.057, -0.205, 0.268),   # основное левое
                          (-0.057, 0.205, 0.268))    # основное правое
    gear_hard: tuple = ((0.494, 0.0, 0.155),         # конец лопасти винта (внизу)
                        (0.520, 0.0, 0.0),           # кок
                        (0.229, 0.0, 0.098),         # днище под мотором
                        (-0.213, 0.0, 0.101),        # днище за крылом
                        (-0.654, 0.0, 0.010),        # хвостовая часть снизу
                        (-0.880, 0.0, -0.010),       # низ руля направления
                        (-0.098, -0.900, -0.158),    # законцовка левая
                        (-0.098, 0.900, -0.158),     # законцовка правая
                        (-0.769, -0.281, -0.049),    # ГО левая
                        (-0.769, 0.281, -0.049),     # ГО правая
                        (-0.761, 0.0, -0.319),       # верх киля
                        (0.0, 0.0, -0.160))          # верх крыла над фюзеляжем
    gear_k:        float = 1000.0  # Н/м, жёсткость на точку
    gear_c:        float = 25.0    # Н·с/м, демпфирование на точку
    gear_mu_roll:  float = 0.05    # сопротивление качению (трава / асфальт)
    gear_mu_side:  float = 0.8     # боковое сцепление колеса
    gear_mu_slide: float = 0.5     # скольжение конструкции по земле
    gear_v_eps:    float = 0.2     # м/с, регуляризация сухого трения (боковое, скольжение)
    gear_v_eps_roll: float = 0.01  # м/с, то же для качения (ползучесть на уклоне 2° — 7 мм/с)
    gear_steer:    float = 1.0     # угол носового колеса / δr
    gear_v_crash:  float = 3.0     # м/с, предельная скорость касания колесом


